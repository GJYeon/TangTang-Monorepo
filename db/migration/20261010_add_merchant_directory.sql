-- tbl_merchant_directory 는 비워 둔다. 데이터는 db/merchant_directory/README.md 의 선택 적재 절차로 넣는다.
-- 비어 있으면 힌트 없이 기존과 똑같이 동작한다.
--
-- tbl_industry_category_map 은 카테고리 "이름"으로 LEFT JOIN 해 넣는다(category_name 은 전역 UNIQUE).
-- seed_category.sql 이 아직 안 돌았으면 category_id 가 NULL 로 들어가고, 그 뒤에 이 파일을 다시
-- 실행하면 채워진다(멱등). category_id 가 NULL 인 업종(B2B·전문서비스)은 소비 카테고리 대응이 없다는 뜻이다.
-- industry_code 에는 FK 를 걸지 않는다 — 상가정보 분기 갱신으로 새 코드가 생겨도 사전 적재가 깨지지 않게.
--
-- 되돌리는 방법: DROP TABLE tbl_merchant_directory; DROP TABLE tbl_industry_category_map;

CREATE TABLE IF NOT EXISTS tbl_industry_category_map (
    industry_code VARCHAR(10)  NOT NULL COMMENT '상권업종소분류코드 (예: I21201)',
    industry_name VARCHAR(100) NOT NULL COMMENT '상권업종 중분류>소분류 이름 (LLM 프롬프트에 그대로 보낸다)',
    category_id   BIGINT       NULL     COMMENT '표준 카테고리. NULL 이면 소비 카테고리 대응 없음',
    PRIMARY KEY (industry_code),
    CONSTRAINT fk_icm_category FOREIGN KEY (category_id) REFERENCES tbl_category (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='상가 업종 → 표준 카테고리 매핑';

CREATE TABLE IF NOT EXISTS tbl_merchant_directory (
    merchant_name_normalized VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL
        COMMENT 'MerchantNameNormalizer 규칙으로 정규화한 상호명',
    industry_code VARCHAR(10)  NOT NULL COMMENT '같은 상호 중 가장 많은 업종',
    store_count   INT          NOT NULL COMMENT '전국 같은 상호 점포 수',
    top_share     DECIMAL(4,3) NOT NULL COMMENT 'industry_code 가 차지하는 비율 (0~1)',
    PRIMARY KEY (merchant_name_normalized)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='상가(상권)정보 상호 사전 (선택 적재)';

